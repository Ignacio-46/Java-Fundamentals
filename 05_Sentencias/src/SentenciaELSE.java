public class SentenciaELSE {
    static void main() {
        //Uso de sentencia else
        var edad = 10;
        //Else significa 'caso contrario' cuando el if no es verdadero
        if (edad >= 18){
            System.out.println("Eres mayor de edad");
        }
        else {
            System.out.println("Eres menor de edad");
        }
    }
}
