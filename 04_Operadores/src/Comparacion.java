public class Comparacion {
    static void main() {
        System.out.println("*** Operadores de Comparación ***");
        int a = 3, b = 2;
        //==
        var resultado = a == b;
        System.out.println("resultado a == b: " + resultado);
        //!=
        resultado = a != b;
        System.out.println("resultado a != b: " + resultado);
        // >
        resultado = a > b;
        System.out.println("resultado a > b: " + resultado);
        // >=
        resultado = a >= b;
        System.out.println("resultado a >= b: " + resultado);
        //<
        resultado = a < b;
        System.out.println("resultado a < b: " + resultado);
        // <=
        resultado = a <= b;
        System.out.println("resultado a <= b: " + resultado);
    }
}
