public class ModificarValores {
    static void main() {
        System.out.println("*** Modificar Valores en Arreglos ***");

        //arreglo
        var entero = new int[5];

        //Modificar valores
        entero[0] = 13;
        entero[1] = 21; // una vez declarada el arreglo se le asigna el valor a traves de los índices
        entero[4] = 62;
        //Los números 13, 21, 62, quedan guardados en el espacio de la memoria
    }
}
