public class Arimeticos {
    static void main() {
        //Operadores Arimeticos
        System.out.println("*** Operadores Arimeticos ***");
        int a = 5, b = 3, resultado; // con int se puede declarar varias variables a la vez con var no

        //Suma +
        resultado = a + b;
        System.out.println("resultado suma = " + resultado);

        //Resta -
        resultado = a - b;
        System.out.println("resultado resta = " + resultado);

        //Multiplicación *
        resultado = a * b;
        System.out.println("resultado multiplicación = " + resultado);

        //División
        resultado = a / b;
        System.out.println("resultado división = " + resultado);

        //Modúlo %
        resultado = a % b;
        System.out.println("resultado modúlo = " + resultado);
    }
}
